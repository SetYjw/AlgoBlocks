import { parser as pythonParser } from '@lezer/python';
import {
  assignmentOps, binary, binaryTypes, block, chain, children, contents, identifier, mathOps,
  nonNumeric, number, parts, quoted, Source, type Block, type Node,
} from './shared';
import type { ParseToBlocksResult } from './types';

const builtinTypes: Record<string, string> = { int: 'int', float: 'double', str: 'string', bool: 'bool' };
const cppType = (type: string) => Object.hasOwn(builtinTypes, type) ? builtinTypes[type] : undefined;
const memberStatements: Record<string, string> = {
  append: 'push_back', appendleft: 'push_front', pop: 'pop_back', popleft: 'pop_front',
  add: 'insert', discard: 'erase', clear: 'clear',
};
const generatorBuiltins = new Set(('False None True and as assert async await break class continue def del elif else except finally for from global if ' +
  'import in is lambda nonlocal not or pass raise return try while with yield ' +
  'abs bool chr dict enumerate float format int isinstance iter len list max min next ord pow print range set sorted str sum ' +
  'bisect collections heapq math re sys').split(' '));
const nameOf = (name: string) => name.startsWith('_user_') &&
  (name.slice(6).startsWith('_') || generatorBuiltins.has(name.slice(6))) ? name.slice(6) : name;

function groups(nodes: Node[]): Node[][] {
  const result: Node[][] = [];
  let group: Node[] = [];
  for (const node of nodes) {
    if (node.name === ',') {
      result.push(group);
      group = [];
    } else group.push(node);
  }
  if (group.length) result.push(group);
  return result;
}

class Python extends Source {
  private types = new Map<string, string>();
  private heaps = new Set<string>();
  private tokenInput = false;
  private generated = false;
  private lineInput = false;

  parse(): ParseToBlocksResult {
    const nodes = this.suite(pythonParser.parse(this.code).topNode);
    const globals: Block[] = [], functions: Block[] = [], loose: Node[] = [];
    const hasMain = nodes.some((n) => this.signature(n)?.name === 'main');
    this.tokenInput = nodes.some((n) => this.tokens(n));
    this.generated = hasMain && nodes.some((n) => this.mainGuard(n));
    this.lineInput = nodes.some((n) => this.lineReader(n));
    this.heaps = this.heapNames(nodes);
    for (const node of nodes) {
      if (this.signature(node) || this.boilerplate(node)) continue;
      if (hasMain || node.name === 'ImportStatement' || /^(?:ClassDefinition|DecoratedStatement|FunctionDefinition)$/.test(node.name)) {
        globals.push(...this.statement(node));
      } else loose.push(node);
    }
    const outer = this.types;
    for (const node of nodes) {
      const signature = this.signature(node);
      if (!signature || this.boilerplate(node)) continue;
      const { name, returnType, params, paramTypes, body } = signature;
      this.types = new Map([...outer, ...paramTypes]);
      const BODY = this.scope(this.suite(body));
      functions.push(name === 'main' ? block('main', { FAST_IO: false }, { BODY })
        : block('func_def', { NAME: nameOf(name), RET_TYPE: returnType, PARAMS: params.join(', ') }, { BODY }));
    }
    this.types = new Map(outer);
    if (!hasMain && (loose.length || !functions.length)) {
      functions.push(block('main', { FAST_IO: false }, { BODY: this.scope(loose) }));
    }
    // Imports converted to blocks are regenerated by the target. Keep an
    // original import when a raw fragment still needs one of its names.
    const pending = [...globals, ...functions];
    const nativeText: string[] = [];
    let hasCin = false, hasGetline = false;
    while (pending.length) {
      const current = pending.pop()!;
      hasCin ||= current.type === 'algo_cin';
      hasGetline ||= current.type === 'algo_getline';
      for (const field of ['CODE', 'EXPR', 'ARGS', 'PARAMS']) {
        if (current.fields?.[field]) nativeText.push(String(current.fields[field]));
      }
      if (current.type.startsWith('algo_func_call_')) nativeText.push(String(current.fields?.NAME));
      for (const entry of Object.values(current.inputs ?? {})) if (entry.block) pending.push(entry.block);
      if (current.next?.block) pending.push(current.next.block);
    }
    const nativeNames = new Set(nativeText.flatMap((text) => text.match(/\b[A-Za-z_]\w*\b/g) ?? []));
    const needsTokens = this.tokenInput && !hasCin && (nativeNames.has('_tokens') || nativeNames.has('_next'));
    const needsLineReader = this.lineInput && !hasGetline && nativeNames.has('_readline');
    if (needsTokens || needsLineReader) nativeNames.add('sys');
    const nativePreamble = nodes.filter((n) => this.importNames(n)?.some((name) => nativeNames.has(name)) ||
      (needsTokens && (this.tokens(n) || this.nextReader(n))) || (needsLineReader && this.lineReader(n)));
    globals.unshift(...nativePreamble.map((n) => this.raw(n)));
    return this.finish([...(globals.length ? [block('global_section', {}, { BODY: chain(globals) })] : []), ...functions]);
  }

  private tokens(node: Node) {
    return node.name === 'AssignStatement' &&
      /^_tokens\s*=\s*iter\(sys\.stdin\.read\(\)\.split\(\)\)$/.test(this.text(node).trim());
  }

  private mainGuard(node: Node) {
    if (node.name !== 'IfStatement') return false;
    const [, test, body, extra] = parts(node);
    if (!test || body?.name !== 'Body' || extra) return false;
    const statements = this.suite(body).filter((n) => n.name !== 'Comment');
    return /^__name__\s*==\s*(['"])__main__\1$/.test(this.text(test)) &&
      statements.length === 1 && /^main\s*\(\s*\)$/.test(this.text(statements[0]));
  }

  private boilerplate(node: Node): boolean {
    const text = this.text(node).trim();
    if (this.mainGuard(node)) return true;
    if (this.importNames(node) || this.lineReader(node)) return true;
    if (this.tokenInput && (this.tokens(node) || this.nextReader(node))) return true;
    return this.generated && /^def _format\(value\):\s+if isinstance\(value, bool\):\s+return int\(value\)\s+if isinstance\(value, float\):\s+return format\(value, "\.6g"\)\s+return value$/.test(text);
  }

  private importNames(node: Node): string[] | undefined {
    if (node.name !== 'ImportStatement') return;
    const text = this.text(node).trim();
    const module = /^import\s+(sys|heapq|collections|math)$/.exec(text);
    if (module) return [module[1]];
    const from = /^from\s+(?:collections|heapq)\s+import\s+(\w+(?:\s*,\s*\w+)*)$/.exec(text);
    if (from) return from[1].split(/\s*,\s*/);
  }

  private lineReader(node: Node): boolean {
    return node.name === 'AssignStatement' &&
      /^_readline\s*=\s*lambda:\s*sys\.stdin\.readline\(\)\.removesuffix\('\\n'\)\.removesuffix\('\\r'\)$/.test(this.text(node).trim());
  }

  private nextReader(node: Node): boolean {
    return node.name === 'AssignStatement' && /^_next\s*=\s*lambda:\s*next\(_tokens\)$/.test(this.text(node).trim());
  }

  private signature(node: Node) {
    if (node.name !== 'FunctionDefinition' || parts(node).some((n) => n.type.isError)) return;
    const [keyword, id, list, fourth, fifth] = parts(node);
    const name = this.text(id), body = fourth?.name === 'Body' ? fourth : fifth;
    if (keyword?.name !== 'def' || id?.name !== 'VariableName' || list?.name !== 'ParamList' || body?.name !== 'Body') return;
    const annotation = fourth?.name === 'TypeDef' ? this.text(contents(fourth)[0]) : '';
    const returnType = annotation === 'None' ? 'void' : (cppType(annotation) ?? 'int');
    if (annotation && annotation !== 'None' && !cppType(annotation)) return;
    const params: string[] = [], paramTypes = new Map<string, string>();
    for (const [arg, ...rest] of groups(parts(list).slice(1, -1))) {
      if (arg?.name !== 'VariableName') return;
      const typeDef = rest[0]?.name === 'TypeDef' ? rest.shift() : undefined;
      const explicit = cppType(this.text(contents(typeDef)[0]));
      if (typeDef && !explicit) return;
      if (rest.length && (rest.length !== 2 || rest[0]?.name !== 'AssignOp' || rest[1].type.isError)) return;
      const initial = rest[1];
      const type = explicit ?? (initial && this.literalType(initial)) ?? 'int', param = this.text(arg);
      // The generator uses C++-style type/name fields even for Python definitions.
      if (initial && /,/.test(this.text(initial))) return;
      params.push(`${type} ${nameOf(param)}${initial ? ` = ${this.text(initial)}` : ''}`);
      paramTypes.set(param, type);
    }
    if (name === 'main' && params.length) return;
    return { name, params, paramTypes, returnType, body };
  }

  private suite(node: Node): Node[] {
    return children(node).filter((n) => n.name !== ':' && n.name !== ';')
      .flatMap((n) => n.name === 'StatementGroup' ? this.suite(n) : [n]);
  }

  private heapNames(nodes: Node[]): Set<string> {
    const heaps = new Set<string>();
    const pending = [...nodes];
    while (pending.length) {
      const node = pending.pop()!;
      if (['FunctionDefinition', 'ClassDefinition'].includes(node.name)) continue;
      const call = this.call(node);
      const heap = this.text(call?.groups[0]?.[0]);
      if (call && /^(?:heapq\.)?heap(?:push|pop)$/.test(call.name) && identifier.test(heap)) heaps.add(heap);
      pending.push(...parts(node));
    }
    return heaps;
  }

  private scope(nodes: Node[]): Block | undefined {
    this.heaps = this.heapNames(nodes);
    return this.statements(nodes);
  }

  private statements(nodes: Node[]): Block | undefined {
    return chain(nodes.flatMap((node) => this.statement(node)));
  }

  private call(node?: Node) {
    if (node?.name !== 'CallExpression') return;
    const [callee, list] = parts(node);
    if (!callee || list?.name !== 'ArgList') return;
    return { callee, list, name: this.text(callee).replace(/\s*\.\s*/g, '.'), groups: groups(parts(list).slice(1, -1)) };
  }

  private simpleArgs(call: NonNullable<ReturnType<Python['call']>>): Node[] | undefined {
    if (call.groups.every((g) => g.length === 1 && !g[0].type.isError && !['*', '**'].includes(g[0].name))) {
      return call.groups.map(([arg]) => arg);
    }
  }

  private literalType(node: Node): string | undefined {
    if (node.name === 'String' && quoted(this.text(node), 'python') !== undefined) return 'string';
    if (node.name === 'Boolean') return 'bool';
    if (node.name === 'Number' || (node.name === 'UnaryExpression' && contents(node)[1]?.name === 'Number')) {
      const text = this.text(node);
      if (/j$/i.test(text)) return;
      return !/^[+-]?\s*0[xob]/i.test(text) && /[.e]/i.test(text) ? 'double' : 'int';
    }
  }

  private indexing(node: Node, VALUE?: Block): Block | undefined {
    const indexes: Node[] = [];
    while (node.name === 'MemberExpression' && node.getChild('[')) {
      const items = contents(node);
      if (items.length !== 2 || /Slice/.test(items[1].name) || node.getChild(':') || node.getChild(',')) return;
      indexes.unshift(items[1]);
      node = items[0];
    }
    if (node.name !== 'VariableName' || ![1, 2].includes(indexes.length)) return;
    const name = this.text(node), VAR = nameOf(name), type = this.types.get(name);
    const first = this.expr(indexes[0]), suffix = VALUE ? 'set' : 'get';
    if (indexes.length === 2) return block(`array2d_${suffix}`, { VAR }, { ROW: first, COL: this.expr(indexes[1]), VALUE });
    if (type === 'map') return block(`map_${suffix}`, { VAR }, { KEY: first, VALUE });
    if (!VALUE && type === 'priority_queue_min' && this.text(indexes[0]) === '0') return block('container_op_expr', { VAR, OP: 'top' });
    return block(`array_${suffix}`, { VAR }, { INDEX: first, VALUE });
  }

  private expr(node: Node): Block {
    const text = this.text(node), nodes = contents(node);
    if (parts(node).some((n) => n.type.isError)) return this.raw(node, true);
    switch (node.name) {
      case 'Number': if (this.literalType(node)) return number(text); break;
      case 'String': {
        const value = quoted(text, 'python');
        if (value !== undefined) return block('string', { TEXT: value });
        break;
      }
      case 'Boolean': return block('bool', { BOOL: text.toLowerCase() });
      case 'VariableName': return block('var_get', { VAR: nameOf(text) });
      case 'ParenthesizedExpression': if (nodes.length === 1) return this.expr(nodes[0]); break;
      case 'BinaryExpression': {
        const [a, op, b] = nodes, symbol = this.text(op);
        const OP = ({ and: '&&', or: '||', '//': '/' } as Record<string, string>)[symbol] ?? symbol;
        if (a && b && Object.hasOwn(binaryTypes, OP)) {
          const kind = binaryTypes[OP];
          if (kind === 'compare' && a.name === 'BinaryExpression' && a.getChild('CompareOp')) break;
          const left = this.expr(a), right = this.expr(b);
          if (['arith', 'bitwise'].includes(kind) && (nonNumeric(left) || nonNumeric(right))) break;
          const bothInt = this.expressionType(left) === 'int' && this.expressionType(right) === 'int';
          if (symbol === '//' && !bothInt) break;
          // The Python generator emits floor division automatically for known integer inputs.
          const A = symbol === '/' && bothInt ? block('cast', { TYPE: 'double' }, { VALUE: left }) : left;
          return binary(kind, OP, A, right);
        }
        break;
      }
      case 'UnaryExpression': {
        const [op, arg] = nodes;
        if (arg && this.text(op) === 'not') {
          const name = this.text(arg);
          if (arg.name === 'VariableName' && this.types.get(name) === 'priority_queue_min') return block('container_op_expr', { VAR: nameOf(name), OP: 'empty' });
          return block('not', {}, { VALUE: this.expr(arg) });
        }
        if (arg && this.text(op) === '-') {
          if (arg.name === 'Number' && this.literalType(arg)) return number(`-${this.text(arg)}`);
          const value = this.expr(arg);
          if (!nonNumeric(value)) return binary('arith', '-', number('0'), value);
        }
        break;
      }
      case 'ConditionalExpression':
        if (nodes.length === 5) return block('ternary', {}, { COND: this.expr(nodes[2]), THEN: this.expr(nodes[0]), ELSE: this.expr(nodes[4]) });
        break;
      case 'MemberExpression': return this.indexing(node) ?? this.raw(node, true);
      case 'CallExpression': return this.expressionCall(node) ?? this.raw(node, true);
    }
    return this.raw(node, true);
  }

  private expressionType(value: Block): string | undefined {
    switch (value.type) {
      case 'algo_number': return !/^[+-]?0[xob]/i.test(String(value.fields?.NUM)) && /[.e]/i.test(String(value.fields?.NUM)) ? 'double' : 'int';
      case 'algo_string': return 'string';
      case 'algo_bool': return 'bool';
      case 'algo_var_get': {
        const name = String(value.fields?.VAR);
        return this.types.get(name) ?? this.types.get(`_user_${name}`);
      }
      case 'algo_array_get': {
        const name = String(value.fields?.VAR);
        const type = this.types.get(name);
        return ['vector', 'deque', 'priority_queue_min'].includes(type ?? '') ? 'int' : type === 'string' ? 'char' : undefined;
      }
      case 'algo_container_op_expr':
        if (value.fields?.OP === 'size') return 'int';
        if (value.fields?.OP === 'top') return 'int';
        break;
      case 'algo_cast': return String(value.fields?.TYPE);
      case 'algo_arith': {
        const a = value.inputs?.A.block, b = value.inputs?.B.block;
        const left = a && this.expressionType(a), right = b && this.expressionType(b);
        if (left && right && ['int', 'double'].includes(left) && ['int', 'double'].includes(right)) {
          return left === 'double' || right === 'double' ? 'double' : 'int';
        }
        if (left === 'string' && right === 'string' && value.fields?.OP === '+') return 'string';
        return;
      }
    }
  }

  private expressionCall(node: Node): Block | undefined {
    const call = this.call(node);
    if (!call) return;
    const args = this.simpleArgs(call);
    const [a, b] = args ?? [], { name, callee, list } = call;
    const fn = name.replace(/^math\./, '');
    if (args?.length === 1 && name === '_format' && this.generated) return this.expr(a);
    if (args?.length === 1 && name === 'bool' && a.name === 'BinaryExpression' &&
      parts(a).some((n) => ['and', 'or'].includes(n.name))) return this.expr(a);
    if (args?.length === 1 && ['len', 'sum', 'min', 'max'].includes(name) && a.name === 'VariableName') {
      const VAR = nameOf(this.text(a));
      return name === 'len' ? block('container_op_expr', { VAR, OP: 'size' }) : block('container_stat', { VAR, OP: name });
    }
    if (args?.length === (['abs', 'sqrt'].includes(fn) ? 1 : 2) && mathOps.includes(fn)) {
      const A = this.expr(a), B = b && this.expr(b);
      if (!nonNumeric(A) && (!B || !nonNumeric(B))) return block('math_func', { FUNC: fn }, { A, B });
      return;
    }
    if (args?.length === 1 && (name === 'int' || name === 'float')) {
      return block('cast', { TYPE: cppType(name)! }, { VALUE: this.expr(a) });
    }
    if (args?.length === 1 && name === 'str') return block('string_op', { VAR: '', OP: 'to_string' }, { ARG: this.expr(a) });
    if (callee.name === 'VariableName' && !generatorBuiltins.has(name) &&
      !['input', 'open', 'eval', 'exec', 'getattr', 'zip', 'super', 'any', 'all', 'heappush', 'heappop'].includes(name)) {
      return block('func_call_expr', { NAME: nameOf(name), ARGS: this.code.slice(list.from + 1, list.to - 1) });
    }
  }

  private print(call: NonNullable<ReturnType<Python['call']>>): Block | undefined {
    const args: Node[] = [];
    let NEWLINE = true, SEP = ' ';
    const keywords = new Set<string>();
    for (const group of call.groups) {
      const [key, op, value] = group;
      if (group.length === 1 && !keywords.size && !key.type.isError && !['*', '**'].includes(key.name)) args.push(key);
      else if (group.length === 3 && op.name === 'AssignOp' && value.name === 'String') {
        const name = this.text(key), text = quoted(this.text(value), 'python');
        if (keywords.has(name)) return;
        keywords.add(name);
        if (name === 'end' && (text === '' || text === '\n')) NEWLINE = text !== '';
        else if (name === 'sep' && (text === '' || text === ' ' || text === '\n')) SEP = text;
        else return;
      } else return;
    }
    if (args.length <= 1) return block('cout', { NEWLINE }, { VALUE: args[0] ? this.expr(args[0]) : block('string', { TEXT: '' }) });
    if (args.length === 2) return block('cout_pair', { SEP, NEWLINE }, { VAL1: this.expr(args[0]), VAL2: this.expr(args[1]) });
  }

  private callStatement(node: Node): Block | undefined {
    const call = this.call(node);
    if (!call) return;
    const { name, callee, list } = call, args = this.simpleArgs(call);
    const [a, b] = args ?? [];
    if (name === 'print') return this.print(call);
    if (call.groups.length === 1 && /^\w+\.sort$/.test(name)) {
      const [keyword, op, value] = call.groups[0];
      if (this.text(keyword) === 'reverse' && op?.name === 'AssignOp' && value?.name === 'Boolean') {
        return block('algorithm_sort', { VAR: nameOf(name.split('.')[0]), MODE: this.text(value) === 'True' ? 'vector_desc' : 'vector_asc' });
      }
    }
    if (!args) return;
    if (/^(?:heapq\.)?heap(?:push|pop)$/.test(name) && args.length === (name.endsWith('push') ? 2 : 1) && a.name === 'VariableName') {
      if (this.types.get(this.text(a)) !== 'priority_queue_min') return;
      return block('container_op_stmt', { VAR: nameOf(this.text(a)), OP: name.endsWith('push') ? 'push' : 'pop' }, { ARG: b && this.expr(b) });
    }
    const [receiver, method, extra] = name.split('.');
    if (method && !extra && identifier.test(receiver)) {
      const VAR = nameOf(receiver);
      if (!args.length && method === 'sort') return block('algorithm_sort', { VAR, MODE: 'vector_asc' });
      if (!args.length && method === 'reverse') return block('algorithm_op', { VAR, OP: 'reverse' });
      if (Object.hasOwn(memberStatements, method) && args.length === Number(['append', 'appendleft', 'add', 'discard'].includes(method))) {
        return block('container_op_stmt', { VAR, OP: memberStatements[method] }, { ARG: a && this.expr(a) });
      }
    }
    if (callee.name === 'VariableName' && !generatorBuiltins.has(name) &&
      !['input', 'open', 'eval', 'exec', 'getattr'].includes(name)) {
      return block('func_call_stmt', { NAME: nameOf(name), ARGS: this.code.slice(list.from + 1, list.to - 1) });
    }
  }

  private input(node: Node): string | undefined {
    const text = this.text(node).replace(/\s/g, '');
    if (text === '_next()') return 'string';
    if (text === '_read_char()') return 'char';
    if (text === 'bool(int(_next()))') return 'bool';
    const conversion = /^(int|float|str)\(_next\(\)\)$/.exec(text);
    return conversion && cppType(conversion[1]) || undefined;
  }

  private container(node: Node, name: string): { CONTAINER: string; ELEM_TYPE: string; ELEM_TYPE2?: string } | undefined {
    const text = this.text(node).replace(/\s/g, '');
    const mapType = /^(?:collections\.)?defaultdict\((int|float|str|bool)\)$/.exec(text);
    if (mapType) return { CONTAINER: 'map', ELEM_TYPE: 'string', ELEM_TYPE2: cppType(mapType[1])! };
    if (text === '[]' || text === 'list()') return { CONTAINER: this.heaps.has(name) ? 'priority_queue_min' : 'vector', ELEM_TYPE: 'int' };
    if (/^(?:collections\.)?deque\(\)$/.test(text)) return { CONTAINER: 'deque', ELEM_TYPE: 'int' };
    if (text === 'set()') return { CONTAINER: 'set', ELEM_TYPE: 'int' };
  }

  private assignment(node: Node): Block[] | undefined {
    const items = parts(node), at = items.findIndex((n) => ['AssignOp', 'UpdateOp'].includes(n.name));
    if (at < 0) return;
    const rawOp = this.text(items[at]), OP = rawOp === '//=' ? '/=' : rawOp;
    if (!assignmentOps.includes(OP)) return;
    const left = items.slice(0, at), right = items.slice(at + 1);
    if (OP === '=' && left.length === 3 && right.length === 3 && left[1].name === ',' && right[1].name === ',' &&
      [left[0], left[2], right[0], right[2]].every((n) => n.name === 'VariableName') &&
      this.text(left[0]) === this.text(right[2]) && this.text(left[2]) === this.text(right[0])) {
      return [block('swap_vars', { A: nameOf(this.text(left[0])), B: nameOf(this.text(left[2])) })];
    }
    const [target, annotation] = left, [rhs] = right;
    if (!target || right.length !== 1 || left.length > 2 || (annotation && annotation.name !== 'TypeDef')) return;
    if (target.name !== 'VariableName') {
      const indexed = OP === '=' && this.indexing(target, this.expr(rhs));
      return indexed ? [indexed] : undefined;
    }
    const name = this.text(target), VAR = nameOf(name), known = this.types.get(name);
    if ((rawOp === '//=' && known !== 'int') || (rawOp === '/=' && known === 'int')) return;
    if (OP === '=') {
      if (this.lineInput && /^_readline\s*\(\s*\)$/.test(this.text(rhs))) return [block('getline', { VAR })];
      const read = this.input(rhs);
      if (read) {
        const input = block('cin', { TARGETS: VAR });
        if (read !== known && !(read === 'int' && known === 'long long')) {
          if (known) return;
          this.types.set(name, read);
          return [block('decl_var', { NAME: VAR, TYPE: read }), input];
        }
        return [input];
      }
      const container = !known && this.container(rhs, name);
      if (container) {
        this.types.set(name, container.CONTAINER);
        const { CONTAINER, ELEM_TYPE, ELEM_TYPE2 } = container;
        return [block('decl_container', { NAME: VAR, CONTAINER, ELEM_TYPE, ...(ELEM_TYPE2 ? { ELEM_TYPE2 } : {}) })];
      }
      if (!known) {
        const explicit = cppType(this.text(contents(annotation)[0]));
        if (annotation && !explicit) return;
        const value = this.expr(rhs);
        const type = explicit ?? this.literalType(rhs) ?? this.expressionType(value);
        if (type && ['int', 'double', 'bool', 'string'].includes(type)) {
          this.types.set(name, type);
          return [block('decl_var', { NAME: VAR, TYPE: type }, { INIT: value })];
        }
        return [block('var_set', { VAR, OP }, { VALUE: value })];
      }
      // Declared Blockly variables are cast on assignment by the Python generator.
      const VALUE = this.expr(rhs), type = this.expressionType(VALUE);
      if (type && ['int', 'double', 'bool', 'string'].includes(known) && type !== known && !this.generated) return;
      return [block('var_set', { VAR, OP }, { VALUE })];
    }
    return [block('var_set', { VAR, OP }, { VALUE: this.expr(rhs) })];
  }

  private conditional(node: Node): Block | undefined {
    const items = parts(node), branches: Array<{ cond: Node; body: Node }> = [];
    let otherwise: Node | undefined;
    for (let i = 0; i < items.length;) {
      const current = items[i++];
      if (current.name === 'else') {
        otherwise = items[i++];
        if (otherwise?.name !== 'Body' || i !== items.length) return;
      } else if (current.name === 'if' || current.name === 'elif') {
        const cond = items[i++], body = items[i++];
        if (!cond || body?.name !== 'Body') return;
        branches.push({ cond, body });
      } else return;
    }
    const branch = (i: number): Block | undefined => {
      const next = branches[i];
      if (!next) return otherwise && this.statements(this.suite(otherwise));
      const COND = this.expr(next.cond), DO = this.statements(this.suite(next.body));
      const elif = branches[i + 1];
      if (elif) return block('if_elseif_else', {}, {
        COND, DO, ELSE_IF_COND: this.expr(elif.cond), ELSE_IF_DO: this.statements(this.suite(elif.body)), ELSE_DO: branch(i + 2),
      });
      return otherwise ? block('if_else', {}, { COND, DO, ELSE_DO: branch(i + 1) }) : block('if', {}, { COND, DO });
    };
    return branch(0);
  }

  private forLoop(node: Node): Block | undefined {
    const items = parts(node), [, id, keyword, source, body] = items;
    if (items.length !== 5 || id?.name !== 'VariableName' || keyword?.name !== 'in' || body?.name !== 'Body') return;
    const name = this.text(id), VAR = nameOf(name);
    const call = this.call(source);
    if (call?.name === 'range') {
      const args = this.simpleArgs(call);
      if (!args || ![1, 2, 3].includes(args.length)) return;
      const stride = args[2], strideText = this.text(stride).replace(/\s/g, '');
      // For dynamic steps the '<' mode emits the stride unchanged in Python.
      const descending = /^-\d/.test(strideText), CMP = descending ? '>' : '<';
      const START = args.length === 1 ? number('0') : this.expr(args[0]);
      const END = this.expr(args[args.length === 1 ? 0 : 1]);
      this.types.set(name, 'int');
      return block('for_range', { TYPE: 'int', VAR, CMP }, {
        START, END, STEP: stride && this.expr(stride), BODY: this.statements(this.suite(body)),
      });
    }
    if (source.name === 'VariableName') {
      return block('for_each', { VAR, CONTAINER: nameOf(this.text(source)), REF: false }, { BODY: this.statements(this.suite(body)) });
    }
  }

  private statement(node: Node): Block[] {
    const items = contents(node), [, cond, body] = items;
    let result: Block | undefined;
    if (parts(node).some((n) => n.type.isError)) return this.text(node).trim() ? [this.raw(node)] : [];
    switch (node.name) {
      case 'Comment': result = block('comment', { TEXT: this.text(node).slice(1).trim() }); break;
      case 'PassStatement': return [];
      case 'AssignStatement': case 'UpdateStatement': return this.assignment(node) ?? [this.raw(node)];
      case 'ExpressionStatement': if (items.length === 1) result = this.callStatement(items[0]); break;
      case 'IfStatement': result = this.conditional(node); break;
      case 'ForStatement': result = this.forLoop(node); break;
      case 'WhileStatement':
        if (cond && body?.name === 'Body' && items.length === 3) {
          const suite = this.suite(body);
          const counter = this.generated && this.text(cond) === 'True' && /^(\w+)\s*-=\s*1$/.exec(this.text(suite[0]));
          if (counter && new RegExp(`^if\\s+${counter[1]}\\s*==\\s*-1\\s*:\\s*break$`).test(this.text(suite[1]).trim())) {
            result = block('while_t', { VAR: nameOf(counter[1]) }, { BODY: this.statements(suite.slice(2)) });
          } else result = block('while', {}, { COND: this.expr(cond), BODY: this.statements(suite) });
        }
        break;
      case 'BreakStatement': case 'ContinueStatement':
        result = block('break_continue', { OP: this.text(items[0]) }); break;
      case 'ReturnStatement':
        if (items.length <= 2 && !node.getChild(',')) result = block('return', {}, { VALUE: cond && this.expr(cond) });
        break;
    }
    return result ? [result] : this.text(node).trim() ? [this.raw(node)] : [];
  }
}

export function parsePythonToBlocks(code: string): ParseToBlocksResult {
  return new Python(code).parse();
}
